// Serialize a table into a cell matrix. Inputs render as "[value]", static
// cells as trimmed textContent — the literals pin both the value AND whether
// the cell is an editable input.
const rowsOf = (table) => Array.from(table.querySelectorAll('tr')).map((tr) =>
  Array.from(tr.querySelectorAll('th,td')).map((cell) => {
    const input = cell.querySelector('input');
    if (input) return input.type === 'checkbox' ? `[${input.checked ? 'x' : ' '}]` : `[${input.value}]`;
    return (cell.textContent || '').trim();
  }));

const sectionOf = (title) => screen.getByText(title).parentElement;
const tableOf = (title) => sectionOf(title).querySelector('table');
// Direct child <div>s of a section: [title, sub, table-or-form, …summaries].
const gridsOf = (title) => Array.from(sectionOf(title).children).filter((el) => el.tagName === 'DIV');

