describe('NpStopLossPricing golden master (hydration slice contract)', () => {
  it('migrates a legacy flat snapshot to layers[] and keeps Structure-page fields on top', async () => {
    // Records saved before the layers refactor: layer 0 lived as top-level
    // attachmentLossRatio / limitLossRatio / epi. The Structure page has
    // since written a fresher layers[] into the slice — it must win, while
    // the engine-only server fields hydrate in underneath.
    apiMock.getNpStopLossPricing.mockResolvedValue({
      inputs: {
        attachmentLossRatio: '70',
        limitLossRatio: '30',
        epi: '5000000',
        loading: '30',
        freqLambda: '12',
        sevMean: '250000',
        sevCv: '0.7',
      },
      outputs: null,
    });
    setAppState({
      slice: { layers: [{ attachmentLossRatio: '85', limitLossRatio: '15', epi: '12000000' }] },
    });
    render(<NpStopLossPricing />);

    await waitFor(() => expect(ctx.replaceSlice).toHaveBeenCalledTimes(1));
    expect(ctx.replaceSlice).toHaveBeenCalledWith('npStopLossInputs', {
      // current (Structure-page) layers beat the migrated legacy layer…
      layers: [{ attachmentLossRatio: '85', limitLossRatio: '15', epi: '12000000' }],
      // …the legacy top-level fields ride along unchanged…
      attachmentLossRatio: '70',
      limitLossRatio: '30',
      epi: '5000000',
      // …server engine fields hydrate in, defaults fill the rest.
      yearlyAggregates: [],
      freqLambda: '12',
      severityType: 'lognormal',
      sevMean: '250000',
      sevCv: '0.7',
      paretoAlpha: '',
      paretoTheta: '',
      weightBurningCost: '50',
      weightExposureRating: '50',
      weightMonteCarlo: '0',
      loading: '30',
      useMonteCarlo: false,
      mcTrials: '10000',
      mcSeed: '1',
    });
  });

  it('leaves the slice untouched when the server has no saved inputs', async () => {
    apiMock.getNpStopLossPricing.mockResolvedValue({ inputs: {}, outputs: null });
    render(<NpStopLossPricing />);
    await waitFor(() => expect(apiMock.getNpStopLossPricing).toHaveBeenCalledTimes(1));
    await waitFor(() => expect(rowsOf(tableOf('Burning Cost · Loss Ratios by UW Year'))).toEqual(BURNING_COST_MATRIX));
    expect(ctx.replaceSlice).not.toHaveBeenCalled();
  });
});
