//     replaceSlice merge-under-current on hydration, and the legacy-shape
//     (top-level attachment/limit/epi) → layers[] migration.
//
// Every literal below was generated by running the real engine
// (client/src/logic/stopLossPricing.js + shared/onLevel.js) against this
// fixture and verified against the pre-refactor screen across 3 runs.
// Monte Carlo is OFF in the main fixture; the MC test relies on the seeded
// mulberry32 PRNG being bit-identical for a fixed seed.
//
// RULE: these expectations may NEVER be edited as part of a refactor. If a
// refactor makes one of these assertions fail, the refactor changed pricing
// behaviour — fix the refactor, not the test.
